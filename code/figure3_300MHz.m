function result = figure3_300MHz(varargin)
%FIGURE3_300MHZ Reproduce the 300 MHz wavefield comparison (f3-2.emf).
% Run from any working directory; original project functions remain unchanged.

ip = inputParser;
ip.addParameter('Recompute', false, @(x)islogical(x) || (isnumeric(x) && isscalar(x)));
ip.parse(varargin{:});

codeDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(codeDir);
addpath(codeDir);
cacheDir = fullfile(projectRoot, 'cache', 'figure3_300MHz');
outputDir = fullfile(projectRoot, 'outputs', 'f3');

cacheFile = fullfile(cacheDir, 'f3.mat');
legacyCacheFile = fullfile(cacheDir, 'wavefield_snapshots_three_methods.mat');
if ~logical(ip.Results.Recompute) && (isfile(cacheFile) || isfile(legacyCacheFile))
    if isfile(cacheFile), cacheFileToLoad = cacheFile; else, cacheFileToLoad = legacyCacheFile; end
    cached = load(cacheFileToLoad, 'metricsTable');
    if ~isfolder(outputDir), mkdir(outputDir); end
    local_copy_figure_formats(cacheDir, outputDir, 'f3');
    local_remove_nonfigure_formats(outputDir);
    result = struct('Cached', true, 'OutputDir', outputDir, ...
        'FigureFile', fullfile(cacheDir, 'f3.fig'), ...
        'PdfFile', fullfile(cacheDir, 'f3.pdf'), ...
        'Metrics', cached.metricsTable);
    fprintf('Figure 3 cache reused; no wavefield recomputation performed.\n');
    return;
end

frequencyMHz = 300;
result = plot_2d_wavefield_fdtd_vs_adaptive( ...
    'ResultFile', '', ...
    'CoarseDx', 0.02, ...
    'ReferenceDx', 0.005, ...
    'Dt', 1e-9/60, ...
    'DomainLength', 12.0, ...
    'DisplayDomainLength', 6.0, ...
    'SnapshotTimes', [20, 30, 40]*1e-9, ...
    'SnapshotTimesRelativeToSourcePeak', true, ...
    'SourceSigma', 0.15*(100/frequencyMHz), ...
    'SourcePosition', [0, 0], ...
    'FrequencyHz', frequencyMHz*1e6, ...
    'StencilHalfWidth', 4, ...
    'UseAngularMapping', false, ...
    'UseWaveletForCoefficients', true, ...
    'CoefficientRegularization', 1e-6, ...
    'ColorLimits', [-1, 1], ...
    'PermittivityModel', @gpr_uniform_permittivity_model_epsr20, ...
    'ModelName', 'uniform_epsr20', ...
    'AdaptiveEpsrSamples', 20, ...
    'IncludeFixedLSDTD', true, ...
    'FixedLSDTDCoefficients', ...
        [1.218159, -0.09397218, 0.01519043, -0.001742128], ...
    'FixedLSDTDCoefficientDefinition', ...
        'original_fixed_M4_LSDTD_coefficients', ...
    'FineReferenceOutputFile', ...
        fullfile(outputDir, 'f3_fine_reference.mat'), ...
    'OutputDir', outputDir, 'FigurePrefix', 'f3');
if ~isfolder(cacheDir), mkdir(cacheDir); end
copyfile(fullfile(outputDir, '*'), cacheDir, 'f');
local_remove_nonfigure_formats(outputDir);
fprintf('Figure 3 recomputed; cache refreshed.\n');
end

function local_copy_figure_formats(sourceDir, targetDir, stem)
for ext = {'.pdf','.emf','.fig'}
    src = fullfile(sourceDir, [stem ext{1}]);
    if isfile(src), copyfile(src, targetDir, 'f'); end
end
end

function local_remove_nonfigure_formats(folder)
files = dir(fullfile(folder, '*'));
for k = 1:numel(files)
    if ~files(k).isdir
        [~,~,ext] = fileparts(files(k).name);
        if ~ismember(lower(ext), {'.pdf','.emf','.fig'}), delete(fullfile(folder,files(k).name)); end
    end
end
end
